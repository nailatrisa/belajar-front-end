// Aritmatika
let a = 10, b = 3;
console.log(a + b);  // 13 (penjumlahan)
console.log(a - b);  // 7  (pengurangan)
console.log(a * b);  // 30 (perkalian)
console.log(a / b);  // 3.33 (pembagian)
console.log(a % b);  // 1  (modulus/sisa bagi)
console.log(a ** b); // 1000 (pangkat)

// Perbandingan
console.log(5 == "5");   // true (loose)
console.log(5 === "5");  // false (strict)
console.log(5 !== 3);   // true
console.log(5 > 3);     // true

// Logika
console.log(true && false);  // AND: false
console.log(true || false);  // OR: true
console.log(!true);          // NOT: false

// Increment/Decrement
let x = 5;
x++;  // 6
x--;  // 5